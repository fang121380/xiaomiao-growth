/* 检索算法：关键字命中得分 */
window.searchKnowledge = function (query, limit = 5) {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();
  const qChars = [...q.replace(/\s+/g, '')];
  return window.CAT_KNOWLEDGE
    .map(item => {
      const fields = [item.title, item.desc, item.cat, ...(item.tags || [])].map(s => (s || '').toLowerCase());
      let score = 0;
      // 完全包含
      if (fields.some(f => f.includes(q))) score += 10;
      // 拆字匹配
      const joined = fields.join(' ');
      if (qChars.every(c => joined.includes(c))) score += 5;
      // 标签命中权重更高
      if ((item.tags || []).some(t => t.toLowerCase().includes(q))) score += 8;
      // 命中多个 tag
      const tagHit = (item.tags || []).filter(t => qChars.some(c => t.toLowerCase().includes(c))).length;
      score += tagHit * 3;
      return { item, score };
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(x => x.item);
};

/* 默认推荐：按类别均匀取热门 */
window.recommendKnowledge = function (limit = 8) {
  const buckets = {};
  window.CAT_KNOWLEDGE.forEach(k => {
    if (!buckets[k.cat]) buckets[k.cat] = [];
    buckets[k.cat].push(k);
  });
  const cats = Object.keys(buckets);
  const result = [];
  let i = 0;
  while (result.length < limit) {
    let added = false;
    for (const c of cats) {
      if (buckets[c][i]) {
        result.push(buckets[c][i]);
        added = true;
        if (result.length >= limit) break;
      }
    }
    if (!added) break;
    i++;
  }
  return result;
};